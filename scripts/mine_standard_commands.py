#!/usr/bin/env python
"""Mines the templates of standard command buttons (`Standard:N`) out of real configurations and writes
`src/cb_standard.rs`. Read-only on the corpora.

    python scripts/mine_standard_commands.py [--out src/cb_standard.rs] [--min-seen 10] [<corpus> ...]
    (default corpora: target/corpus/dental target/corpus/ut2)

For every `Reference/FormStream.bin` it finds the button tables of the command panels
(`{5,T1,T2,1,nAct,Action x nAct,nGroups,Group x nGroups}`), takes every standard action
(`{6|7,guid,1,fbe38877-...,{6,srcId,typeGuid,CODE,{1,0|99,groupGuid,groupCode,flag},0,1},mask,...}`) and the button
record that refers to it, and votes:
  * the body `(srcId, typeGuid, origin)` and the button fields `(b2,b3,b5,b8,b9,b11)` by the most frequent variant
    per code ("any form") and, where a form class has >= 5 observations and a different winner, per form class;
  * the caption: the most frequent Russian text of the button record.
The form class comes from the main attribute of the sibling `Form.xml` (same rule as `form_class` in
`src/cb_standard.rs`). Codes seen fewer than --min-seen times get no template.
"""
import argparse
import collections
import glob
import os
import re
import sys
from pathlib import Path

STANDARD_KIND = "fbe38877-"
ROOT = Path(__file__).resolve().parent.parent
NONE = "(без подписи в корпусах)"

# code -> meaning (from the most frequent captions / tooltips of both corpora); a code not listed gets its mined
# caption, or NONE when the buttons of the corpora have no caption
MEANING = {
    6: "Новая группа", 8: "Переместить в группу", 9: "Иерархический просмотр", 10: "Новая группа",
    11: "Просмотр по владельцу", 20: "Интервал дат", 21: "Поиск по номеру", 24: "Провести",
    29: "Отмена проведения", 38: "Пометка удаления", 40: "Ввести на основании", 53: "Отбор и сортировка",
    80: "Добавить", 82: "Скопировать", 83: "Удалить", 84: "Изменить", 85: "Вверх", 86: "Вниз",
    88: "Сортировка по возрастанию", 89: "Сортировка по убыванию", 90: "Обновить", 91: "Отбор по значению",
    93: "Отключить отбор", 94: "Закончить редактирование", 95: "Выбрать", 97: "Настройка списка",
    99: "Вывести список", 106: "Представление", 107: "Подробно", 120: "Включить все", 121: "Выключить все",
    140: "Записать", 141: "OK (в работе «Записать и закрыть»)", 142: "Закрыть",
    143: "Сохранить значения", 144: "Восстановить значения", 145: "Скопировать", 146: "Перечитать",
    147: "Найти в списке", 300: "Справка", 320: "Назад", 321: "Вперёд",
}

HEADER = '''// @generated by scripts/mine_standard_commands.py; do not edit by hand.
//! Templates of standard command buttons (`Standard:N`) mined from real forms.
//!
//! A standard action record is `{6|7,guid,1,fbe38877-...,{6,srcId,typeGuid,CODE,{1,kind,groupGuid,groupCode,flag},0,1},0}`;
//! its body is NOT a function of the code alone. For every code the most frequent variant over __TOTAL__ standard
//! actions of the two reference configurations is stored (class `""` = any form), and for a form class with at least
//! five observations and a different winner a class row. The button fields `b2,b3,b5,b8,b9,b11` are voted the same
//! way; the caption is the most frequent Russian text of the button record. The form class is derived from the name
//! of the main attribute of the form ([`form_class`]).

/// One standard command: the code, its meaning, the default Russian caption and how often it was seen.
#[derive(Debug, Clone, Copy)]
pub struct StdCode {
    pub code: u32,
    pub meaning: &'static str,
    pub caption: &'static str,
    /// Standard actions with this code in the corpora.
    pub seen: u32,
    /// Distinct bodies among them.
    pub bodies: u32,
}

/// The winning body and button fields of a code for a form class (`""` = any form).
#[derive(Debug, Clone, Copy)]
pub struct StdTemplate {
    pub code: u32,
    pub class: &'static str,
    /// `(srcId, typeGuid, originKind, originGuid, originCode, originFlag)` of the action body.
    pub body: [&'static str; 6],
    /// `(b2, b3, b5, b8, b9, b11)` of the button record.
    pub button: [&'static str; 6],
    /// Observations of the winning body.
    pub votes: u32,
    /// Observations in this scope.
    pub of: u32,
}

/// Form class of a form by the name of its main attribute (`"Other"` when there is none).
pub fn form_class(main_attribute: &str) -> &'static str {
    if main_attribute.ends_with("Список") || main_attribute.starts_with("Журнал") || main_attribute.ends_with("Выбор") {
        "List"
    } else if main_attribute.starts_with("Документ") {
        "Document"
    } else if main_attribute.starts_with("Справочник") {
        "Catalog"
    } else {
        "Other"
    }
}

'''


def parse(text):
    """Minimal 1C brace-text parser: lists are `list`, atoms are `str`, quoted strings keep a leading NUL."""
    i, n = 0, len(text)

    def val():
        nonlocal i
        if text[i] == "{":
            i += 1
            out = []
            while True:
                while i < n and text[i] in " \r\n\t":
                    i += 1
                if text[i] == "}":
                    i += 1
                    return out
                if text[i] == ",":
                    i += 1
                    continue
                out.append(val())
        if text[i] == '"':
            j = i + 1
            s = []
            while True:
                if text[j] == '"':
                    if j + 1 < n and text[j + 1] == '"':
                        s.append('"')
                        j += 2
                        continue
                    break
                s.append(text[j])
                j += 1
            i = j + 1
            return "\x00" + "".join(s)
        j = i
        while text[j] not in ",}\r\n":
            j += 1
        s = text[i:j]
        i = j
        return s.strip()

    while text[i] != "{":
        i += 1
    return val()


def is_guid(s):
    return isinstance(s, str) and len(s) == 36 and s[8] == "-"


def tables(n, out):
    """Every button table below `n`."""
    if not isinstance(n, list):
        return
    if len(n) >= 6 and n[0] == "5" and is_guid(n[1]) and isinstance(n[4], str) and n[4].isdigit():
        na = int(n[4])
        if len(n) >= 6 + na and all(isinstance(n[5 + i], list) and len(n[5 + i]) >= 5 for i in range(na)):
            out.append(n)
    for c in n:
        tables(c, out)


def form_class(xml):
    m = re.search(r'<MainAttribute attributeId="(\d+)"', xml)
    if not m:
        return "Other"
    a = re.search(r'<Attribute id="%s" name="([^"]*)"' % m.group(1), xml)
    name = a.group(1) if a else ""
    if name.endswith("Список") or name.startswith("Журнал") or name.endswith("Выбор"):
        return "List"
    if name.startswith("Документ"):
        return "Document"
    if name.startswith("Справочник"):
        return "Catalog"
    return "Other"


def caption_ru(cap):
    """The Russian text of a localized string `{1,N,{lang,text}...}`, or None."""
    if not isinstance(cap, list):
        return None
    for item in cap[2:]:
        if isinstance(item, list) and len(item) == 2 and item[0] == "\x00ru":
            return item[1][1:]
    return None


def observations(corpora):
    """Yields (form class, code, body key, button key, ru caption) of every standard button."""
    for corpus in corpora:
        for p in glob.glob(os.path.join(corpus, "**", "FormStream.bin"), recursive=True):
            xml_path = os.path.join(os.path.dirname(os.path.dirname(p)), "Form.xml")
            cls = "Other"
            if os.path.exists(xml_path):
                cls = form_class(open(xml_path, encoding="utf-8").read(40000))
            try:
                tree = parse(open(p, encoding="utf-8-sig").read())
            except Exception as e:  # a stream this parser cannot read is skipped
                print("skip", p, e, file=sys.stderr)
                continue
            ts = []
            tables(tree, ts)
            for t in ts:
                na = int(t[4])
                acts = {t[5 + i][1]: t[5 + i] for i in range(na)}
                try:
                    ng = int(t[5 + na])
                except (ValueError, TypeError):
                    continue
                btn = {}
                for gi in range(ng):
                    g = t[6 + na + gi]
                    if not isinstance(g, list) or len(g) < 6:
                        continue
                    for i in range(int(g[4])):
                        btn[g[5 + 2 * i]] = g[6 + 2 * i]
                for guid, a in acts.items():
                    if not (isinstance(a[3], str) and a[3].startswith(STANDARD_KIND)):
                        continue
                    body = a[4]
                    if not (isinstance(body, list) and len(body) >= 7 and isinstance(body[4], list) and len(body[4]) >= 5):
                        continue
                    b = btn.get(guid)
                    if not b or len(b) < 13:
                        continue
                    o = body[4]
                    yield (
                        cls,
                        int(body[3]),
                        (body[1], body[2], o[1], o[2], o[3], o[4]),
                        (b[2], b[3], b[5], b[8], b[9], b[11]),
                        caption_ru(b[4]),
                    )


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def arr(t):
    return "[" + ", ".join(rust_str(x) for x in t) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("corpora", nargs="*")
    ap.add_argument("--out", default=str(ROOT / "src" / "cb_standard.rs"))
    ap.add_argument("--min-seen", type=int, default=10)
    args = ap.parse_args()
    corpora = args.corpora or [str(ROOT / "target/corpus/dental"), str(ROOT / "target/corpus/ut2")]
    seen = collections.Counter()
    bodies = collections.defaultdict(collections.Counter)
    scope = collections.defaultdict(lambda: collections.defaultdict(lambda: (collections.Counter(), collections.Counter())))
    caps = collections.defaultdict(collections.Counter)
    for cls, code, body, button, cap in observations(corpora):
        seen[code] += 1
        bodies[code][body] += 1
        for key in ("", cls):
            scope[code][key][0][body] += 1
            scope[code][key][1][button] += 1
        if cap:
            caps[code][cap] += 1
    print("observations:", sum(seen.values()), "codes:", len(seen), file=sys.stderr)
    codes = sorted(c for c, n in seen.items() if n >= args.min_seen)

    def row(code, key):
        bc, btc = scope[code][key]
        body, votes = bc.most_common(1)[0]
        return "    StdTemplate { code: %d, class: %s, body: %s, button: %s, votes: %d, of: %d }," % (
            code, rust_str(key), arr(body), arr(btc.most_common(1)[0][0]), votes, sum(bc.values()))

    out = [HEADER.replace("__TOTAL__", str(sum(seen[c] for c in codes))), "pub const CODES: &[StdCode] = &["]
    for c in codes:
        cap = caps[c].most_common(1)[0][0] if caps[c] else ""
        out.append("    StdCode { code: %d, meaning: %s, caption: %s, seen: %d, bodies: %d }," % (
            c, rust_str(MEANING.get(c) or cap or NONE), rust_str(cap), seen[c], len(bodies[c])))
    out += ["];", "", "pub const TEMPLATES: &[StdTemplate] = &["]
    for c in codes:
        out.append(row(c, ""))
        base = tuple(x.most_common(1)[0][0] for x in scope[c][""])
        for key in sorted(k for k in scope[c] if k):
            bc, btc = scope[c][key]
            if sum(bc.values()) >= 5 and (bc.most_common(1)[0][0], btc.most_common(1)[0][0]) != base:
                out.append(row(c, key))
    out += ["];", ""]
    Path(args.out).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote", args.out, "codes", len(codes), file=sys.stderr)


if __name__ == "__main__":
    main()
